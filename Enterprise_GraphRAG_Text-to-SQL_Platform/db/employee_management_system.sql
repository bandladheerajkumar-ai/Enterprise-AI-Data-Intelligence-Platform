CREATE OR REPLACE FUNCTION fn_validate_leave_request()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.end_date < NEW.start_date THEN
        RAISE EXCEPTION 'Leave end date cannot be earlier than start date';
    END IF;
    IF NEW.approver_id IS NOT NULL AND NEW.approver_id = NEW.employee_id THEN
        RAISE EXCEPTION 'Employee cannot approve their own leave request';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_leave_request
BEFORE INSERT OR UPDATE ON leave_requests
FOR EACH ROW EXECUTE FUNCTION fn_validate_leave_request();

CREATE OR REPLACE FUNCTION fn_prevent_overlapping_asset_assignment()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM employee_assets ea
        WHERE ea.asset_id = NEW.asset_id
          AND ea.employee_asset_id <> COALESCE(NEW.employee_asset_id, -1)
          AND ea.returned_on IS NULL
          AND NEW.returned_on IS NULL
    ) THEN
        RAISE EXCEPTION 'Asset % is already assigned', NEW.asset_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_prevent_overlapping_asset_assignment
BEFORE INSERT OR UPDATE ON employee_assets
FOR EACH ROW EXECUTE FUNCTION fn_prevent_overlapping_asset_assignment();

CREATE OR REPLACE FUNCTION fn_update_project_assignment_count()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_project_id BIGINT;
BEGIN
    v_project_id := COALESCE(NEW.project_id, OLD.project_id);
    UPDATE projects p
    SET current_assignment_count = (
        SELECT COUNT(*) FROM employee_project_assignments epa
        WHERE epa.project_id = v_project_id
          AND (epa.assigned_to IS NULL OR epa.assigned_to >= CURRENT_DATE)
    )
    WHERE p.project_id = v_project_id;
    RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_update_project_assignment_count
AFTER INSERT OR UPDATE OR DELETE ON employee_project_assignments
FOR EACH ROW EXECUTE FUNCTION fn_update_project_assignment_count();

CREATE OR REPLACE FUNCTION fn_compute_attendance_hours()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.check_in IS NOT NULL AND NEW.check_out IS NOT NULL THEN
        NEW.total_hours := ROUND((EXTRACT(EPOCH FROM (NEW.check_out - NEW.check_in)) / 3600)::numeric, 2);
    ELSIF NEW.status IN ('Absent','Holiday') THEN
        NEW.total_hours := 0;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_compute_attendance_hours
BEFORE INSERT OR UPDATE ON attendance
FOR EACH ROW EXECUTE FUNCTION fn_compute_attendance_hours();

