-- Employee Management System for PostgreSQL
-- Run this file directly with:
-- psql -d your_database -f employee_management_system.sql

BEGIN;

DROP TABLE IF EXISTS employee_assets CASCADE;
DROP TABLE IF EXISTS assets CASCADE;
DROP TABLE IF EXISTS employee_training CASCADE;
DROP TABLE IF EXISTS training_programs CASCADE;
DROP TABLE IF EXISTS performance_reviews CASCADE;
DROP TABLE IF EXISTS payroll CASCADE;
DROP TABLE IF EXISTS leave_requests CASCADE;
DROP TABLE IF EXISTS attendance CASCADE;
DROP TABLE IF EXISTS employee_skills CASCADE;
DROP TABLE IF EXISTS skills CASCADE;
DROP TABLE IF EXISTS employee_project_assignments CASCADE;
DROP TABLE IF EXISTS projects CASCADE;
DROP TABLE IF EXISTS clients CASCADE;
DROP TABLE IF EXISTS employee_managers CASCADE;
DROP TABLE IF EXISTS employees CASCADE;
DROP TABLE IF EXISTS teams CASCADE;
DROP TABLE IF EXISTS departments CASCADE;
DROP TABLE IF EXISTS designations CASCADE;
DROP TABLE IF EXISTS offices CASCADE;
DROP TABLE IF EXISTS locations CASCADE;

CREATE TABLE locations (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city VARCHAR(80) NOT NULL,
    state VARCHAR(80) NOT NULL,
    country VARCHAR(80) NOT NULL DEFAULT 'India',
    postal_code VARCHAR(10) NOT NULL CHECK (postal_code ~ '^[0-9]{6}$'),
    timezone VARCHAR(50) NOT NULL DEFAULT 'Asia/Kolkata',
    UNIQUE (city, state)
);

CREATE TABLE offices (
    office_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL REFERENCES locations(location_id) ON UPDATE CASCADE,
    office_code VARCHAR(20) NOT NULL UNIQUE,
    office_name VARCHAR(120) NOT NULL,
    address_line1 VARCHAR(180) NOT NULL,
    address_line2 VARCHAR(180),
    phone VARCHAR(15) NOT NULL CHECK (phone ~ '^[6-9][0-9]{9}$'),
    is_head_office BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE designations (
    designation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL UNIQUE,
    level_no SMALLINT NOT NULL CHECK (level_no BETWEEN 1 AND 12),
    min_salary NUMERIC(12,2) NOT NULL CHECK (min_salary >= 0),
    max_salary NUMERIC(12,2) NOT NULL CHECK (max_salary >= min_salary)
);

CREATE TABLE departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id BIGINT NOT NULL REFERENCES offices(office_id) ON UPDATE CASCADE,
    department_code VARCHAR(20) NOT NULL UNIQUE,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    budget NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (budget >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE teams (
    team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(department_id) ON UPDATE CASCADE,
    team_code VARCHAR(20) NOT NULL UNIQUE,
    team_name VARCHAR(100) NOT NULL,
    UNIQUE (department_id, team_name)
);

CREATE TABLE employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(20) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    gender VARCHAR(20) NOT NULL CHECK (gender IN ('Female','Male','Non-binary','Prefer not to say')),
    date_of_birth DATE NOT NULL CHECK (date_of_birth <= CURRENT_DATE - INTERVAL '18 years'),
    email VARCHAR(160) NOT NULL UNIQUE CHECK (email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'),
    phone VARCHAR(15) NOT NULL UNIQUE CHECK (phone ~ '^[6-9][0-9]{9}$'),
    hire_date DATE NOT NULL CHECK (hire_date <= CURRENT_DATE),
    department_id BIGINT NOT NULL REFERENCES departments(department_id) ON UPDATE CASCADE,
    team_id BIGINT NOT NULL REFERENCES teams(team_id) ON UPDATE CASCADE,
    designation_id BIGINT NOT NULL REFERENCES designations(designation_id) ON UPDATE CASCADE,
    office_id BIGINT NOT NULL REFERENCES offices(office_id) ON UPDATE CASCADE,
    employment_status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (employment_status IN ('Active','On Leave','Resigned','Terminated')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE employee_managers (
    manager_relation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    manager_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE RESTRICT,
    effective_from DATE NOT NULL,
    effective_to DATE,
    CHECK (employee_id <> manager_id),
    CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

CREATE TABLE clients (
    client_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_code VARCHAR(20) NOT NULL UNIQUE,
    client_name VARCHAR(140) NOT NULL UNIQUE,
    industry VARCHAR(80) NOT NULL,
    location_id BIGINT NOT NULL REFERENCES locations(location_id) ON UPDATE CASCADE,
    contact_email VARCHAR(160) NOT NULL UNIQUE CHECK (contact_email ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'),
    contact_phone VARCHAR(15) NOT NULL CHECK (contact_phone ~ '^[6-9][0-9]{9}$')
);

CREATE TABLE projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(client_id) ON UPDATE CASCADE,
    department_id BIGINT NOT NULL REFERENCES departments(department_id) ON UPDATE CASCADE,
    project_code VARCHAR(20) NOT NULL UNIQUE,
    project_name VARCHAR(160) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Planned' CHECK (status IN ('Planned','Active','On Hold','Completed','Cancelled')),
    budget NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (budget >= 0),
    current_assignment_count INTEGER NOT NULL DEFAULT 0 CHECK (current_assignment_count >= 0),
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE employee_project_assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    project_id BIGINT NOT NULL REFERENCES projects(project_id) ON DELETE CASCADE,
    role_on_project VARCHAR(80) NOT NULL,
    allocation_percent NUMERIC(5,2) NOT NULL CHECK (allocation_percent > 0 AND allocation_percent <= 100),
    assigned_from DATE NOT NULL,
    assigned_to DATE,
    billable BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (assigned_to IS NULL OR assigned_to >= assigned_from),
    UNIQUE (employee_id, project_id, assigned_from)
);

CREATE TABLE skills (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR(100) NOT NULL UNIQUE,
    skill_category VARCHAR(80) NOT NULL
);

CREATE TABLE employee_skills (
    employee_skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES skills(skill_id) ON DELETE CASCADE,
    proficiency_level VARCHAR(20) NOT NULL CHECK (proficiency_level IN ('Beginner','Intermediate','Advanced','Expert')),
    years_experience NUMERIC(4,1) NOT NULL DEFAULT 0 CHECK (years_experience >= 0),
    certified BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (employee_id, skill_id)
);

CREATE TABLE attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    attendance_date DATE NOT NULL,
    check_in TIME,
    check_out TIME,
    status VARCHAR(20) NOT NULL CHECK (status IN ('Present','Absent','Half Day','Work From Home','Holiday')),
    total_hours NUMERIC(4,2) NOT NULL DEFAULT 0 CHECK (total_hours >= 0 AND total_hours <= 24),
    UNIQUE (employee_id, attendance_date),
    CHECK (check_out IS NULL OR check_in IS NULL OR check_out >= check_in)
);

CREATE TABLE leave_requests (
    leave_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    approver_id BIGINT REFERENCES employees(employee_id) ON DELETE SET NULL,
    leave_type VARCHAR(30) NOT NULL CHECK (leave_type IN ('Casual','Sick','Earned','Maternity','Paternity','Bereavement','Unpaid')),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected','Cancelled')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date),
    CHECK (approver_id IS NULL OR approver_id <> employee_id)
);

CREATE TABLE payroll (
    payroll_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    payroll_month DATE NOT NULL,
    basic_salary NUMERIC(12,2) NOT NULL CHECK (basic_salary >= 0),
    hra NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (hra >= 0),
    allowances NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (allowances >= 0),
    deductions NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (deductions >= 0),
    net_salary NUMERIC(12,2) GENERATED ALWAYS AS (basic_salary + hra + allowances - deductions) STORED,
    payment_status VARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK (payment_status IN ('Pending','Paid','On Hold')),
    paid_on DATE,
    UNIQUE (employee_id, payroll_month)
);

CREATE TABLE performance_reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    reviewer_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE RESTRICT,
    review_period_start DATE NOT NULL,
    review_period_end DATE NOT NULL,
    rating NUMERIC(3,2) NOT NULL CHECK (rating >= 1 AND rating <= 5),
    goals_met_percent NUMERIC(5,2) NOT NULL CHECK (goals_met_percent >= 0 AND goals_met_percent <= 100),
    comments TEXT,
    reviewed_at DATE NOT NULL DEFAULT CURRENT_DATE,
    CHECK (review_period_end >= review_period_start),
    CHECK (employee_id <> reviewer_id)
);

CREATE TABLE training_programs (
    training_program_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(department_id) ON UPDATE CASCADE,
    program_code VARCHAR(20) NOT NULL UNIQUE,
    program_name VARCHAR(140) NOT NULL,
    provider VARCHAR(120) NOT NULL,
    duration_hours NUMERIC(5,2) NOT NULL CHECK (duration_hours > 0),
    mode VARCHAR(20) NOT NULL CHECK (mode IN ('Online','Classroom','Hybrid'))
);

CREATE TABLE employee_training (
    employee_training_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    training_program_id BIGINT NOT NULL REFERENCES training_programs(training_program_id) ON DELETE CASCADE,
    enrolled_on DATE NOT NULL,
    completed_on DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Enrolled' CHECK (status IN ('Enrolled','In Progress','Completed','Dropped')),
    score NUMERIC(5,2) CHECK (score IS NULL OR (score >= 0 AND score <= 100)),
    CHECK (completed_on IS NULL OR completed_on >= enrolled_on),
    UNIQUE (employee_id, training_program_id, enrolled_on)
);

CREATE TABLE assets (
    asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id BIGINT NOT NULL REFERENCES offices(office_id) ON UPDATE CASCADE,
    asset_tag VARCHAR(40) NOT NULL UNIQUE,
    asset_type VARCHAR(50) NOT NULL,
    brand VARCHAR(60) NOT NULL,
    model VARCHAR(80) NOT NULL,
    serial_number VARCHAR(80) NOT NULL UNIQUE,
    purchase_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Assigned','Repair','Retired'))
);

CREATE TABLE employee_assets (
    employee_asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    asset_id BIGINT NOT NULL REFERENCES assets(asset_id) ON DELETE RESTRICT,
    assigned_on DATE NOT NULL,
    returned_on DATE,
    condition_on_issue VARCHAR(20) NOT NULL CHECK (condition_on_issue IN ('New','Good','Fair')),
    condition_on_return VARCHAR(20) CHECK (condition_on_return IS NULL OR condition_on_return IN ('Good','Fair','Damaged')),
    CHECK (returned_on IS NULL OR returned_on >= assigned_on)
);

CREATE UNIQUE INDEX ux_employee_managers_current ON employee_managers(employee_id) WHERE effective_to IS NULL;
CREATE UNIQUE INDEX ux_employee_assets_current ON employee_assets(asset_id) WHERE returned_on IS NULL;
CREATE INDEX idx_offices_location_id ON offices(location_id);
CREATE INDEX idx_departments_office_id ON departments(office_id);
CREATE INDEX idx_teams_department_id ON teams(department_id);
