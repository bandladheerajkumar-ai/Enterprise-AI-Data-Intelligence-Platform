    DO UPDATE SET basic_salary = EXCLUDED.basic_salary, hra = EXCLUDED.hra,
                  allowances = EXCLUDED.allowances, deductions = EXCLUDED.deductions,
                  payment_status = 'Pending', paid_on = NULL;
