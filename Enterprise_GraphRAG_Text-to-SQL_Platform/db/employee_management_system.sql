WITH allocation AS (SELECT employee_id, SUM(allocation_percent) AS allocation_percent FROM employee_project_assignments WHERE assigned_to IS NULL OR assigned_to >= CURRENT_DATE GROUP BY employee_id), hours AS (SELECT employee_id, SUM(total_hours) AS jan_hours FROM attendance WHERE attendance_date BETWEEN DATE '2026-01-01' AND DATE '2026-01-31' GROUP BY employee_id) SELECT e.employee_code, e.first_name || ' ' || e.last_name AS employee_name, d.department_name, COALESCE(a.allocation_percent,0) AS allocation_percent, COALESCE(h.jan_hours,0) AS jan_hours, p.net_salary, ROUND(p.net_salary / NULLIF(COALESCE(h.jan_hours,0),0),2) AS cost_per_recorded_hour FROM employees e JOIN departments d ON d.department_id = e.department_id LEFT JOIN allocation a ON a.employee_id = e.employee_id LEFT JOIN hours h ON h.employee_id = e.employee_id LEFT JOIN payroll p ON p.employee_id = e.employee_id AND p.payroll_month = DATE '2026-01-01' ORDER BY cost_per_recorded_hour DESC NULLS LAST;
